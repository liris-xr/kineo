import argparse
from kineo.datasets.egohumans.egohumans_preprocess import preprocess_egohumans

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "dataset_dir",
        type=str,
        help="Path to the directory where the dataset was downloaded",
    )
    parser.add_argument(
        "--skip-extract",
        action="store_true",
        help="Skip extracting the tarfiles and only preprocess the annotations",
    )
    parser.add_argument(
        "--skip-annotations-generation",
        action="store_true",
        help="Skip generating the annotations for each subsequence. Only the global sequences file will be generated.",
    )
    parser.add_argument(
        "--use-original-bboxes",
        action="store_true",
        help="Use the original bboxes instead of the ones generated by the model",
    )
    parser.add_argument(
        "--sequences",
        type=str,
        nargs="+",
        help="List of sequences to generate the annotations for (e.g. fencing_001 fencing_002). If not provided, all sequences will be processed except if --skip-annotations-generation is set.",
        default=None,
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Show the annotations in a window",
    )
    parser.add_argument(
        "--merge-translation-tolerance",
        type=float,
        help="Tolerance for merging translation extrinsics annotations (in meters). In particular, this is used to filter truly static cameras.",
        default=0.02,
    )
    parser.add_argument(
        "--merge-rotation-tolerance",
        type=float,
        help="Tolerance for merging rotation extrinsics annotations (in degrees). In particular, this is used to filter truly static cameras.",
        default=1.0,
    )

    args = parser.parse_args()

    preprocess_egohumans(
        args.dataset_dir,
        skip_extract=args.skip_extract,
        skip_annotations_generation=args.skip_annotations_generation,
        use_original_bboxes=args.use_original_bboxes,
        sequences=args.sequences,
        show=args.show,
        merge_translation_tolerance=args.merge_translation_tolerance,
        merge_rotation_tolerance=args.merge_rotation_tolerance,
    )
